#!/usr/bin/env python3
"""Generate the test contracts FINDINGS.md refers to, from the reference fixture.

    python make_test_contracts.py      # writes test-contracts/*.json

- variant.json      design.md P7: dates removed from 27 of 52 sources (timeline must hide),
                    terms as strings, no x/y, one topic with `related`, a bridge source,
                    edge sources, skill-only fields, zero propositions.
- no-xy.json        the fixture with x/y stripped (P2: positions must not change).
- synthetic-150.json  P2 timing: 150 sources in 6 topics. Synthetic: example.org URLs,
                    placeholder titles, no real claims.
- bad-dangling.json P8: the fixture with one stance pointing at a missing article.
"""
import copy
import json
from pathlib import Path

HERE = Path(__file__).parent
FIXTURE = HERE.parent / "fixtures" / "reference-map-jevons.json"
OUT = HERE / "test-contracts"


def strip_xy(c):
    for a in c["articles"]:
        a.pop("x", None)
        a.pop("y", None)
    return c


def main():
    fx = json.loads(FIXTURE.read_text(encoding="utf-8"))
    OUT.mkdir(exist_ok=True)

    v = strip_xy(copy.deepcopy(fx))
    v["_note"] = "Generated by make_test_contracts.py from the reference fixture (design.md P7 variant)."
    v["schema_version"] = 1
    v["queries"] = [{"q": "jevons paradox", "purpose": "overview", "results_kept": 8},
                    {"q": "rebound effect criticism", "purpose": "dissent", "results_kept": 3}]
    for k, a in enumerate(v["articles"]):
        if k % 2 == 0 or k == 51:
            a["publish_date"] = None  # 27 of 52 undated
        a["read_depth"] = "full" if k % 3 else "snippet"
    for cl in v["clusters"]:
        cl["terms"] = [t[0] for t in cl["terms"]]
    v["clusters"][5]["related"] = [{"cluster_id": 4, "strength": 1.0}, {"cluster_id": 0, "strength": 0.2}]
    in4 = [a for a in v["articles"] if a["cluster_id"] == 4]
    in0 = [a for a in v["articles"] if a["cluster_id"] == 0]
    in2 = [a for a in v["articles"] if a["cluster_id"] == 2]
    in4[0]["also_cluster_id"] = 5          # bridge
    in4[0]["summary"] = "Synthetic test summary: a bridge source between the two AI topics."
    in0[0]["fit"] = "edge"
    in0[1]["fit"] = "edge"
    in2[0]["fit"] = "edge"
    for a in v["articles"]:
        a.setdefault("fit", "core")
    v["propositions"] = []
    (OUT / "variant.json").write_text(json.dumps(v, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")

    n = strip_xy(copy.deepcopy(fx))
    (OUT / "no-xy.json").write_text(json.dumps(n, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")

    sizes = [45, 35, 25, 20, 15, 10]
    s = {"_note": "Synthetic 150-source contract for layout timing (design.md P2). Not real sources.",
         "schema_version": 1, "topic": "synthetic timing test", "article_count": 150,
         "clusters": [], "articles": [], "propositions": []}
    k = 0
    for cid, size in enumerate(sizes):
        s["clusters"].append({"cluster_id": cid, "label": f"Synthetic topic {cid + 1}",
                              "description": "Placeholder topic for timing.", "article_count": size,
                              "terms": ["alpha", "beta", "gamma"]})
        for j in range(size):
            s["articles"].append({"id": f"syn{k:04d}", "url": f"https://example.org/s/{k}", "domain": "example.org",
                                  "title": f"Synthetic source {k}", "publish_date": f"{2010 + k % 16}",
                                  "cluster_id": cid, "fit": "edge" if j % 9 == 0 else "core"})
            k += 1
    stances = ["agrees", "agrees", "qualifies", "disputes"]
    for p in range(12):
        members = [a for a in s["articles"] if int(a["id"][3:]) % 12 == p][:9]
        s["propositions"].append({"position": p, "statement": f"Synthetic proposition {p + 1}.",
                                  "stances": [{"article_id": a["id"], "stance": stances[i % 4],
                                               "claim": "Placeholder claim."} for i, a in enumerate(members)]})
    (OUT / "synthetic-150.json").write_text(json.dumps(s, indent=1) + "\n", encoding="utf-8")

    b = copy.deepcopy(fx)
    b["propositions"][3]["stances"][0]["article_id"] = "does-not-exist"
    (OUT / "bad-dangling.json").write_text(json.dumps(b, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    print("wrote", ", ".join(sorted(p.name for p in OUT.glob("*.json"))))


if __name__ == "__main__":
    main()
